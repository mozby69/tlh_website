) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_billing_periods (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  rental_id BIGINT UNSIGNED NOT NULL,
  period_no INT UNSIGNED NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  due_date DATE NOT NULL,
  rent_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  finalized_at DATETIME NULL,
  finalized_by INT UNSIGNED NULL,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rental_period (rental_id,period_no),
  KEY idx_rental_period_dates (period_start,period_end),
  KEY idx_rental_period_rental (rental_id,period_start),
  CONSTRAINT fk_rental_period_rental FOREIGN KEY (rental_id) REFERENCES rentals(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_period_admin FOREIGN KEY (finalized_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_charges (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  rental_id BIGINT UNSIGNED NOT NULL,
  billing_period_id BIGINT UNSIGNED NULL,
  charge_type_id INT UNSIGNED NOT NULL,
  description VARCHAR(255) NULL,
  amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  charged_at DATETIME NOT NULL,
  created_by INT UNSIGNED NULL,
  legacy_source VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rental_charge_legacy (legacy_source),
  KEY idx_rental_charge_rental (rental_id,charged_at),
  KEY idx_rental_charge_period (billing_period_id),
  KEY idx_rental_charge_type (charge_type_id),
  CONSTRAINT fk_rental_charge_rental FOREIGN KEY (rental_id) REFERENCES rentals(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_charge_period FOREIGN KEY (billing_period_id) REFERENCES rental_billing_periods(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_charge_type FOREIGN KEY (charge_type_id) REFERENCES rental_charge_types(id) ON DELETE RESTRICT,
  CONSTRAINT fk_rental_charge_admin FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
