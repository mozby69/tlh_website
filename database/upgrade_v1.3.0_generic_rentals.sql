-- TLH v1.3.0 - Generic Rentals Engine
-- Existing Food Stall data is preserved and migrated into the new generic tables.

CREATE TABLE IF NOT EXISTS rental_categories (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  slug VARCHAR(120) NOT NULL,
  category_type ENUM('space','equipment','other') NOT NULL DEFAULT 'space',
  default_availability_mode ENUM('exclusive','quantity') NOT NULL DEFAULT 'exclusive',
  default_billing_mode ENUM('one_time','monthly') NOT NULL DEFAULT 'one_time',
  allow_flexible_dates TINYINT(1) NOT NULL DEFAULT 1,
  allow_utilities TINYINT(1) NOT NULL DEFAULT 0,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rental_category_name (name),
  UNIQUE KEY uq_rental_category_slug (slug),
  KEY idx_rental_category_active (is_active,sort_order),
  CONSTRAINT fk_rental_category_admin FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rentables (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  category_id INT UNSIGNED NOT NULL,
  code VARCHAR(60) NOT NULL,
  name VARCHAR(160) NOT NULL,
  location VARCHAR(160) NULL,
  availability_mode ENUM('exclusive','quantity') NOT NULL DEFAULT 'exclusive',
  total_quantity INT UNSIGNED NOT NULL DEFAULT 1,
  billing_mode ENUM('one_time','monthly') NOT NULL DEFAULT 'one_time',
  allow_flexible_dates TINYINT(1) NOT NULL DEFAULT 1,
  allow_utilities TINYINT(1) NOT NULL DEFAULT 0,
  notes TEXT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  legacy_food_stall_id INT UNSIGNED NULL,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rentable_code (code),
  UNIQUE KEY uq_rentable_legacy_food_stall (legacy_food_stall_id),
  KEY idx_rentable_category (category_id,is_active),
  KEY idx_rentable_active (is_active,code),
  CONSTRAINT fk_rentable_category FOREIGN KEY (category_id) REFERENCES rental_categories(id) ON DELETE RESTRICT,
  CONSTRAINT fk_rentable_admin FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rentals (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  reference_no VARCHAR(40) NOT NULL,
  client_name VARCHAR(160) NOT NULL,
  contact_number VARCHAR(50) NULL,
  organization VARCHAR(160) NULL,
  schedule_type ENUM('continuous','flexible') NOT NULL DEFAULT 'continuous',
  billing_mode ENUM('one_time','monthly') NOT NULL DEFAULT 'one_time',
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  base_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  amount_paid DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  payment_status ENUM('unpaid','partial','paid') NOT NULL DEFAULT 'unpaid',
  security_deposit_required DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  status ENUM('active','completed','cancelled') NOT NULL DEFAULT 'active',
  is_complimentary TINYINT(1) NOT NULL DEFAULT 0,
  complimentary_reason VARCHAR(1000) NULL,
  complimentary_by INT UNSIGNED NULL,
  complimentary_at DATETIME NULL,
  final_billing_notes TEXT NULL,
  final_billed_at DATETIME NULL,
  final_billed_by INT UNSIGNED NULL,
  original_end_date DATE NULL,
  early_end_reason VARCHAR(255) NULL,
  early_ended_at DATETIME NULL,
  early_ended_by INT UNSIGNED NULL,
  notes TEXT NULL,
  cancelled_reason VARCHAR(255) NULL,
  completed_at DATETIME NULL,
  legacy_food_stall_rental_id BIGINT UNSIGNED NULL,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rental_reference (reference_no),
  UNIQUE KEY uq_rental_legacy_food_stall (legacy_food_stall_rental_id),
  KEY idx_rental_dates (start_date,end_date),
  KEY idx_rental_status (status,start_date,end_date),
  KEY idx_rental_billing (billing_mode,status),
  CONSTRAINT fk_rental_created_admin FOREIGN KEY (created_by) REFERENCES admins(id) ON DELETE SET NULL,
  CONSTRAINT fk_rental_complimentary_admin FOREIGN KEY (complimentary_by) REFERENCES admins(id) ON DELETE SET NULL,
  CONSTRAINT fk_rental_final_admin FOREIGN KEY (final_billed_by) REFERENCES admins(id) ON DELETE SET NULL,
  CONSTRAINT fk_rental_early_admin FOREIGN KEY (early_ended_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  rental_id BIGINT UNSIGNED NOT NULL,
  rentable_id INT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL DEFAULT 1,
  agreed_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  notes VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_rental_item_rental (rental_id),
  KEY idx_rental_item_rentable (rentable_id,rental_id),
  CONSTRAINT fk_rental_item_rental FOREIGN KEY (rental_id) REFERENCES rentals(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_item_rentable FOREIGN KEY (rentable_id) REFERENCES rentables(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_dates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  rental_id BIGINT UNSIGNED NOT NULL,
  rental_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'scheduled',
  released_at DATETIME NULL,
  released_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rental_date (rental_id,rental_date),
  KEY idx_rental_dates_date (rental_date,status),
  KEY idx_rental_dates_rental (rental_id,status,rental_date),
  CONSTRAINT fk_rental_date_rental FOREIGN KEY (rental_id) REFERENCES rentals(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_date_admin FOREIGN KEY (released_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_payments (
