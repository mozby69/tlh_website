  KEY idx_rental_payment_admin (recorded_by),
  CONSTRAINT fk_rental_payment_rental FOREIGN KEY (rental_id) REFERENCES rentals(id) ON DELETE CASCADE,
  CONSTRAINT fk_rental_payment_admin FOREIGN KEY (recorded_by) REFERENCES admins(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rental_deposit_transactions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
